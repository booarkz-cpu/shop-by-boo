SHA_A, SHA_B = "a" * 64, "b" * 64


def release(repo, tag):
    if repo == "XTLS/Xray-core":
        t = tag or "v25.10.15"
        return {"tag_name": t, "assets": [
            {"name": "Xray-linux-64.zip", "browser_download_url": f"https://github.com/XTLS/Xray-core/releases/download/{t}/Xray-linux-64.zip",
             "digest": f"sha256:{SHA_A}"},
            {"name": "Xray-linux-arm64-v8a.zip", "digest": f"sha256:{SHA_B}",
             "browser_download_url": f"https://github.com/XTLS/Xray-core/releases/download/{t}/Xray-linux-arm64-v8a.zip"}]}
    return {"tag_name": "v2.2.29", "assets": [
        {"name": f"wgcf_2.2.29_linux_{a}", "digest": f"sha256:{SHA_A}",
         "browser_download_url": f"https://github.com/ViRb3/wgcf/releases/download/v2.2.29/wgcf_2.2.29_linux_{a}"} for a in ("amd64", "arm64")]}


@pytest.mark.asyncio
async def test_release_lookup_takes_githubs_sha256(monkeypatch):
    async def fetch(repo, tag):
        return release(repo, tag)
    monkeypatch.setattr(rw_releases, "fetch", fetch)
    version, files = await rw_releases.xray_core(None)
    assert version == "v25.10.15" and files["x86_64"]["sha256"] == SHA_A and files["aarch64"]["url"].endswith("arm64-v8a.zip")
    version, files = await rw_releases.wgcf()
    assert files["x86_64"]["url"].endswith("_linux_amd64")
    with pytest.raises(rw_releases.ReleaseError):
        await rw_releases.xray_core("latest; rm -rf /")

    async def no_digest(repo, tag):
        out = release(repo, tag)
        out["assets"][0].pop("digest")
        return out
    monkeypatch.setattr(rw_releases, "fetch", no_digest)
    with pytest.raises(rw_releases.ReleaseError, match="SHA-256"):
        await rw_releases.xray_core(None)

    async def elsewhere(repo, tag):
        out = release(repo, tag)
        out["assets"][0]["browser_download_url"] = "https://evil.example/Xray-linux-64.zip"
        return out
    monkeypatch.setattr(rw_releases, "fetch", elsewhere)
    with pytest.raises(rw_releases.ReleaseError, match="адрес"):
        await rw_releases.xray_core(None)


def test_module_plans_and_files():
    servers = {1: {"name": "fi-1", "host": "93.184.216.10", "arch": "x86_64"}, 2: {"name": "de-1", "host": "93.184.216.11", "arch": "aarch64"}}
    base_plan = dict(mode="add_node", node_server_ids=[1, 2])
    files = {"x86_64": {"url": "https://github.com/XTLS/Xray-core/releases/download/v25.10.15/Xray-linux-64.zip", "sha256": SHA_A},
             "aarch64": {"url": "https://github.com/XTLS/Xray-core/releases/download/v25.10.15/Xray-linux-arm64-v8a.zip", "sha256": SHA_B}}
    plan = rw_plan.PlanIn(**base_plan, xray_core="v25.10.15", module=rw_plan.ModuleRun(name="xray_core", version="v25.10.15", release=files))
    built = rw_plan.build_action("module", plan, servers)
    kinds = [(s["kind"], s["server_id"]) for s in built["steps"]]
    assert kinds == [("node_module", 1), ("write_files", 1), ("compose_up", 1), ("node_module", 2), ("write_files", 2), ("compose_up", 2),
                     ("verify", None)]
    assert built["steps"][3]["params"]["sha256"] == SHA_B, "each server gets the file of its architecture"
    with pytest.raises(ValueError):
        rw_plan.build_action("module", rw_plan.PlanIn(**base_plan, module=rw_plan.ModuleRun(name="xray_core", version="v1.0.0", release={})), servers)
    node = rw_plan.node_compose("key", 2222, selfsteal=True, xray_core=True)
    assert node.count("    volumes:") == 1 and "./xray-core/xray:/usr/local/bin/xray:ro" in node and "/dev/shm:/dev/shm:rw" in node
    ipv6 = rw_plan.build_action("module", rw_plan.PlanIn(**base_plan, module=rw_plan.ModuleRun(name="ipv6", enabled=False, server_ids=[2])), servers)
    assert [(s["kind"], s["server_id"], s["params"]["enabled"]) for s in ipv6["steps"]] == [("node_module", 2, False)]
    with pytest.raises(ValueError):  # only servers of this installation
        rw_plan.build_action("module", rw_plan.PlanIn(**base_plan, module=rw_plan.ModuleRun(name="ipv6", server_ids=[9])), servers)
    with pytest.raises(ValidationError):
        rw_plan.PlanIn(**base_plan, xray_checker_server_id=9)
    checker = rw_plan.PlanIn(**base_plan, xray_checker_server_id=1, module=rw_plan.ModuleRun(name="xray_checker"))
    assert [s["kind"] for s in rw_plan.build_action("module", checker, servers)["steps"]] == ["write_files", "compose_up", "node_module"]
    assert ("write_files", "xray_checker") in [(s["kind"], s["params"].get("component"))
                                               for s in rw_plan.build_action("update", checker.model_copy(update={"module": None}), servers)["steps"]]
    env = rw_plan.checker_env("https://sub.example.com/s/abc", 300, "checker", "p" * 32)
    assert "METRICS_HOST=127.0.0.1" in env and "METRICS_PROTECTED=true" in env and "SUBSCRIPTION_URL=https://sub.example.com/s/abc" in env
    with pytest.raises(ValueError):
        rw_plan.checker_env("https://x.example.com/$(id)", 300, "checker", "p")
    assert "network_mode: host" in rw_plan.checker_compose() and rw_plan.CHECKER_IMAGE in rw_plan.checker_compose()
    # The scripts refuse anything but the files GitHub publishes, and check SHA-256 before installing.
    assert "https://github.com/XTLS/Xray-core/releases/download/v*/Xray-linux-*.zip" in rw_steps.XRAY_CORE
    assert rw_steps.XRAY_CORE.index("sha256sum -c") < rw_steps.XRAY_CORE.index('install -m 0755 "$tmp/x/xray"')
    assert "Table = off" in rw_steps.WARP and rw_steps.WARP.index("sha256sum -c") < rw_steps.WARP.index("./wgcf register")
    assert 'NB_SETUP_KEY="$key"' in rw_steps.NETBIRD and "--setup-key " not in rw_steps.NETBIRD, "the key never reaches argv"
    assert "signed-by=/usr/share/keyrings/netbird-archive-keyring.gpg" in rw_steps.NETBIRD


