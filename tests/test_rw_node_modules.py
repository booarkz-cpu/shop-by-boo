"""v28.70.0 (stage 12, part B): modules on the node's server through the wizard — SelfSteal first.

SelfSteal: Caddy on the node gets the certificate of the node's domain and serves a template site on a unix socket;
Xray REALITY on port 443 sends foreign connections there (``dest`` = the socket, ``xver: 1``). The wizard writes the
Caddy files, mounts /dev/shm into the node, creates the REALITY profile and the host in the panel, binds the node to
it and checks the site on the socket. The real install runs in CI (tests/live/test_install_live.py)."""
import pytest
from pydantic import ValidationError

import test_rw_installer as base
