def test_selfsteal_plan_rules_and_files():
    with pytest.raises(ValidationError):  # one domain — one node
        rw_plan.PlanIn(mode="add_node", node_server_ids=[2, 3], selfsteal_domain="n.example.com", tls="internal")
    with pytest.raises(ValidationError):  # port 443 of the panel's server belongs to its Caddy
        rw_plan.PlanIn(mode="panel_node", panel_server_id=1, panel_domain="p.example.com", selfsteal_domain="n.example.com", tls="internal")
    with pytest.raises(ValidationError):
        rw_plan.PlanIn(mode="node", node_server_ids=[2], selfsteal_domain="bad domain")
    plan = rw_plan.PlanIn(mode="node", node_server_ids=[2], selfsteal_domain="Node.Example.com", acme_email="a@example.com")
    assert plan.selfsteal_domain == "node.example.com"
    built = rw_plan.build_plan(plan, {2: {"name": "n2", "host": "93.184.216.40"}}, "https://panel.shop.example")
    kinds = [(s["kind"], s["params"].get("component")) for s in built["steps"]]
    assert kinds.index(("write_files", "selfsteal")) < kinds.index(("write_files", "node")) < kinds.index(("selfsteal_profile", None)) \
        < kinds.index(("register_node", None))
    pre = built["steps"][0]["params"]
    assert "selfsteal" in pre["roles"] and pre["domains"] == ["node.example.com"]
    caddy = rw_plan.selfsteal_caddyfile("node.example.com", "acme", "a@example.com")
    assert "bind unix//dev/shm/selfsteal.sock" in caddy and "proxy_protocol" in caddy and "email a@example.com" in caddy
    assert "local_certs" in rw_plan.selfsteal_caddyfile("node.example.com", "internal", None)
    node = rw_plan.node_compose("key", 2222, selfsteal=True)
    assert "/dev/shm:/dev/shm:rw" in node and "/dev/shm" not in rw_plan.node_compose("key", 2222)
    page = rw_plan.selfsteal_page("docs", "node.example.com")
    assert "Документация" in page and "<script" not in page and "http" not in page.split("<body>")[1]
    actions = rw_plan.build_action("update", plan, {2: {"name": "n2", "host": "93.184.216.40"}})
    assert ("write_files", "selfsteal") in [(s["kind"], s["params"].get("component")) for s in actions["steps"]]
    checks = {c["key"]: c["status"] for c in rw_steps.evaluate(rw_steps.parse_facts("\n".join(base.facts() + ["listen=443 nginx"])),
                                                               ["node", "selfsteal"], [], 2222, "93.184.216.40", "internal")}
    assert checks["port_443"] == "error" and checks["port_80"] == "ok"


@pytest.mark.asyncio
async def test_selfsteal_install_end_to_end(database, fleet, monkeypatch):
    db = database
    monkeypatch.setitem(base.SCRIPTS, rw_steps.SELFSTEAL_CHECK, "selfsteal_check")
    monkeypatch.setattr(settings, "remnawave_url", "https://panel.shop.example")
    monkeypatch.setattr(settings, "remnawave_token", "shop-token")
    panel = {"profiles": {}, "hosts": {}, "nodes": {}}
    calls = []

    class Client:
        async def _request(self, method, path, **kw):
            body = kw.get("json")
            calls.append((method, path))
            if path == "/api/keygen":
                return {"pubKey": "k"}
            if path == "/api/system/tools/x25519/generate":
                return {"keypairs": [{"publicKey": "PUB", "privateKey": "PRIV"}]}
            if path == "/api/config-profiles" and method == "POST":
                panel["profiles"]["prof-ss"] = body
                return {"uuid": "prof-ss", "inbounds": [{"uuid": "in-ss"}]}
            if path == "/api/config-profiles":
                return {"configProfiles": [{"uuid": "default", "inbounds": [{"uuid": "in-d"}]},
                                           *({"uuid": u, "inbounds": [{"uuid": "in-ss"}]} for u in panel["profiles"])]}
            if path == "/api/hosts" and method == "POST":
                panel["hosts"]["host-ss"] = body
                return {"uuid": "host-ss"}
            if path == "/api/nodes" and method == "POST":
                panel["nodes"]["n-1"] = body
                return {"uuid": "n-1"}
            if path == "/api/nodes/n-1":
                return {"isConnected": True}
            return {}
    import app.remnawave as remnawave
    monkeypatch.setattr(remnawave, "RemnawaveClient", Client)
    monkeypatch.setattr(rw_steps.socket, "gethostbyname", lambda host: "93.184.216.1")
    server = await add_server(db, fleet, "node-ss", "198.51.100.30", purpose=["node"])
    await rw_api.check_server(server["id"], db, ADMIN)
    approved = await plan_and_approve(db, rw_plan.PlanIn(mode="node", node_server_ids=[server["id"]], selfsteal_domain="node.example.com",
                                                         selfsteal_template="corgi", tls="internal"))
    await run_all(db)
    got = await rw_api.get_installation(approved["id"], db, ADMIN)
    assert got["status"] == "succeeded", got["error"]
    host = fleet["198.51.100.30"]
    assert {"/opt/remnawave-selfsteal", "/opt/remnanode"} <= host.up
    assert "bind unix//dev/shm/selfsteal.sock" in host.files[("/opt/remnawave-selfsteal", "Caddyfile")]
    assert "Дневник корги" in host.files[("/opt/remnawave-selfsteal", "index.html")]
    assert "/dev/shm:/dev/shm:rw" in host.files[("/opt/remnanode", "docker-compose.yml")]
    reality = panel["profiles"]["prof-ss"]["config"]["inbounds"][0]["streamSettings"]["realitySettings"]
    assert reality["dest"] == rw_plan.SELFSTEAL_SOCKET and reality["xver"] == 1 and reality["serverNames"] == ["node.example.com"]
    assert reality["privateKey"] == "PRIV"
    assert panel["hosts"]["host-ss"]["address"] == "node.example.com" and panel["hosts"]["host-ss"]["sni"] == "node.example.com"
    assert panel["nodes"]["n-1"]["configProfile"] == {"activeConfigProfileUuid": "prof-ss", "activeInbounds": ["in-ss"]}
    assert ("selfsteal_check", ("node.example.com",)) in host.calls
    assert any(r[-1] == "web" for r in host.rules), "ufw: 80 and 443 open for everyone"
