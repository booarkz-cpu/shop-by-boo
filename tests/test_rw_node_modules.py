    ipv6 = rw_plan.build_action("module", rw_plan.PlanIn(**base_plan, module=rw_plan.ModuleRun(name="ipv6", enabled=False, server_ids=[2])), servers)
    assert [(s["kind"], s["server_id"], s["params"]["enabled"]) for s in ipv6["steps"]] == [("node_module", 2, False)]
    with pytest.raises(ValueError):  # only servers of this installation
        rw_plan.build_action("module", rw_plan.PlanIn(**base_plan, module=rw_plan.ModuleRun(name="ipv6", server_ids=[9])), servers)
    with pytest.raises(ValidationError):
        rw_plan.PlanIn(**base_plan, xray_checker_server_id=9)
    checker = rw_plan.PlanIn(**base_plan, xray_checker_server_id=1, module=rw_plan.ModuleRun(name="xray_checker"))
    assert [s["kind"] for s in rw_plan.build_action("module", checker, servers)["steps"]] == ["write_files", "compose_up", "node_module"]
    assert ("write_files", "xray_checker") in [(s["kind"], s["params"].get("component"))
                                               for s in rw_plan.build_action("update", checker.model_copy(update={"module": None}), servers)["steps"]]
    env = rw_plan.checker_env("https://sub.example.com/s/abc", 300, "checker", "p" * 32)
    assert "METRICS_HOST=127.0.0.1" in env and "METRICS_PROTECTED=true" in env and "SUBSCRIPTION_URL=https://sub.example.com/s/abc" in env
    with pytest.raises(ValueError):
        rw_plan.checker_env("https://x.example.com/$(id)", 300, "checker", "p")
    assert "network_mode: host" in rw_plan.checker_compose() and rw_plan.CHECKER_IMAGE in rw_plan.checker_compose()
    # The scripts refuse anything but the files GitHub publishes, and check SHA-256 before installing.
    assert "https://github.com/XTLS/Xray-core/releases/download/v*/Xray-linux-*.zip" in rw_steps.XRAY_CORE
    assert rw_steps.XRAY_CORE.index("sha256sum -c") < rw_steps.XRAY_CORE.index('install -m 0755 "$tmp/x/xray"')
    assert "Table = off" in rw_steps.WARP and rw_steps.WARP.index("sha256sum -c") < rw_steps.WARP.index("./wgcf register")
    assert 'NB_SETUP_KEY="$key"' in rw_steps.NETBIRD and "--setup-key " not in rw_steps.NETBIRD, "the key never reaches argv"
    assert "signed-by=/usr/share/keyrings/netbird-archive-keyring.gpg" in rw_steps.NETBIRD


