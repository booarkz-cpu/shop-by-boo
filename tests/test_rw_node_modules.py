@pytest.mark.asyncio
async def test_orion_subscription_page_is_pinned(monkeypatch):
    """v28.77.0: Orion (legiz-ru/Orion, MIT) instead of the stock page — exactly the pinned file, mounted read-only."""
    import hashlib
    assert "volumes" not in rw_plan.subpage_compose()
    assert '"./index.html:/opt/app/frontend/index.html:ro"' in rw_plan.subpage_compose("orion")
    assert rw_plan.ORION["commit"] in rw_plan.ORION["url"] and "/main/" not in rw_plan.ORION["url"]
    plan = rw_plan.PlanIn(mode="subpage", subpage_server_id=3, sub_domain="sub.example.com", tls="internal",
                          subpage_template="orion")
    built = rw_plan.build_plan(plan, {3: {"name": "s3", "host": "93.184.216.41"}}, "https://panel.shop.example")
    assert any("Orion" in c for c in built["servers"]["3"]["changes"])
    good = b"<html>orion</html>"
    monkeypatch.setitem(rw_plan.ORION, "sha256", hashlib.sha256(good).hexdigest())

    async def fetch(url):
        assert url == rw_plan.ORION["url"]
        return good
    monkeypatch.setattr(rw_steps, "fetch_bytes", fetch)

    async def panel(ctx):
        return "https://panel.example.com", "token"
    monkeypatch.setattr(rw_steps, "_panel_url_and_token", panel)
    ctx = rw_steps.Context(plan=plan, servers={}, secrets=rw_steps.new_secrets(), state={})
    files = await rw_steps.files_for(ctx, "subscription_page", 3)
    assert files["index.html"] == "<html>orion</html>" and "index.html:ro" in files["docker-compose.yml"]

    async def tampered(url):
        return b"<html>changed</html>"
    monkeypatch.setattr(rw_steps, "fetch_bytes", tampered)
    with pytest.raises(rw_steps.StepError):
        await rw_steps.files_for(ctx, "subscription_page", 3)
    assert 'chmod 0644 "$dir/$name.rw-new"' in rw_steps.WRITE  # the page is readable by the container's user
