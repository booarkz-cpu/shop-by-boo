def test_selfsteal_plan_rules_and_files():
    with pytest.raises(ValidationError):  # one domain — one node
        rw_plan.PlanIn(mode="add_node", node_server_ids=[2, 3], selfsteal_domain="n.example.com", tls="internal")
    with pytest.raises(ValidationError):  # port 443 of the panel's server belongs to its Caddy
        rw_plan.PlanIn(mode="panel_node", panel_server_id=1, panel_domain="p.example.com", selfsteal_domain="n.example.com", tls="internal")
    with pytest.raises(ValidationError):
        rw_plan.PlanIn(mode="node", node_server_ids=[2], selfsteal_domain="bad domain")
    plan = rw_plan.PlanIn(mode="node", node_server_ids=[2], selfsteal_domain="Node.Example.com", acme_email="a@example.com")
    assert plan.selfsteal_domain == "node.example.com"
    built = rw_plan.build_plan(plan, {2: {"name": "n2", "host": "93.184.216.40"}}, "https://panel.shop.example")
    kinds = [(s["kind"], s["params"].get("component")) for s in built["steps"]]
    assert kinds.index(("write_files", "selfsteal")) < kinds.index(("write_files", "node")) < kinds.index(("selfsteal_profile", None)) \
        < kinds.index(("register_node", None))
    pre = built["steps"][0]["params"]
    assert "selfsteal" in pre["roles"] and pre["domains"] == ["node.example.com"]
    caddy = rw_plan.selfsteal_caddyfile("node.example.com", "acme", "a@example.com")
    assert "bind unix//dev/shm/selfsteal.sock" in caddy and "proxy_protocol" in caddy and "email a@example.com" in caddy
    assert "local_certs" in rw_plan.selfsteal_caddyfile("node.example.com", "internal", None)
    node = rw_plan.node_compose("key", 2222, selfsteal=True)
    assert "/dev/shm:/dev/shm:rw" in node and "/dev/shm" not in rw_plan.node_compose("key", 2222)
    page = rw_plan.selfsteal_page("docs", "node.example.com")
    assert "Документация" in page and "<script" not in page and "http" not in page.split("<body>")[1]
    actions = rw_plan.build_action("update", plan, {2: {"name": "n2", "host": "93.184.216.40"}})
    assert ("write_files", "selfsteal") in [(s["kind"], s["params"].get("component")) for s in actions["steps"]]
    checks = {c["key"]: c["status"] for c in rw_steps.evaluate(rw_steps.parse_facts("\n".join(base.facts() + ["listen=443 nginx"])),
                                                               ["node", "selfsteal"], [], 2222, "93.184.216.40", "internal")}
    assert checks["port_443"] == "error" and checks["port_80"] == "ok"


