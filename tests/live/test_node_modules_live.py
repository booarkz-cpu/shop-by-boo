"""v28.70.0 (stage 12): SelfSteal and node modules for real (scripts/ci/rw-install-live.sh with RW_LIVE_TEST).

The newest panel runs from its official compose on 127.0.0.1:3000 (scripts/ci/remnawave-live.sh, PANEL_ONLY_ENV)
and the shop is connected to it. The wizard installs «node only» with SelfSteal on the runner over SSH: Caddy with
its internal CA serves the template site on /dev/shm/selfsteal.sock, the REALITY profile and host are created in the
panel and the node connects. Then:

* a TLS client without REALITY keys on port 443 gets the template site — that is what an outside observer sees;
* IPv6 off and on again (sysctl);
* the newest Xray core from XTLS/Xray-core, checked by the SHA-256 GitHub published, and back to the bundled core;
* the Xray Checker image pulls (its digest is printed to be pinned in rw_plan.CHECKER_IMAGE);
* v28.82.0: «Транспорты ноды» — xHTTP, gRPC (REALITY) and Hysteria2 with the SelfSteal certificate: the real panel takes
  the profile, Xray listens on TCP 4443, TCP 8443 and UDP 443, hosts exist; then back to TCP + REALITY only.

Skipped unless the installer variables and REMNAWAVE_URL / REMNAWAVE_TOKEN are set."""
import os
import subprocess
import time
from pathlib import Path

import pytest

from app import rw_api, rw_plan
from app.config import settings
from test_install_live import ADMIN, FINGERPRINT, HOST, KEY_FILE, containers, db, run  # noqa: F401

URL = os.environ.get("REMNAWAVE_URL")
TOKEN = os.environ.get("REMNAWAVE_TOKEN")
pytestmark = pytest.mark.skipif(not (HOST and KEY_FILE and FINGERPRINT and URL and TOKEN), reason="no panel and test server")
DOMAIN = "node.corgi.test"


def sh(*args: str) -> str:
    return subprocess.run(list(args), capture_output=True, text=True, timeout=120).stdout


def site() -> str:
    """The page on port 443 for a client without REALITY keys; right after a node restart the panel is still
    sending the node its config, so Xray's inbound comes up a few seconds later."""
    page = ""
    for _ in range(30):
        page = sh("curl", "-sk", "--max-time", "10", "--resolve", f"{DOMAIN}:443:127.0.0.1", f"https://{DOMAIN}/")
        if "Документация" in page:
            break
        time.sleep(3)
    return page


async def module(db, installation_id: int, **kw) -> dict:
    planned = await rw_api.action(installation_id, rw_api.ActionIn(action="module", module=rw_api.ModuleIn(**kw)), db, ADMIN)
    print("plan:", [s["title"] for s in planned["plan"]["steps"]])
    await rw_api.approve(planned["id"], rw_api.ApproveIn(plan_sha256=planned["plan_sha256"]), db, ADMIN)
    done = await run(db, planned["id"])
    assert done["status"] == "succeeded", (kw, done["error"])
    return done


@pytest.mark.asyncio
async def test_selfsteal_node_and_modules(db, monkeypatch):
    monkeypatch.setattr(settings, "remnawave_url", URL)
    monkeypatch.setattr(settings, "remnawave_token", TOKEN)
    server = await rw_api.create_server(rw_api.ServerIn(
        name="ci-node", host=HOST, ssh_user="root", auth_method="key", private_key=Path(KEY_FILE).read_text(),
        host_key_fingerprint=FINGERPRINT, purpose=["node"]), db, ADMIN)
    checked = await rw_api.check_server(server["id"], db, ADMIN)
    print({c["key"]: (c["status"], c["detail"]) for c in checked["checks"]})
    planned = await rw_api.plan_installation(rw_plan.PlanIn(mode="node", node_server_ids=[server["id"]], selfsteal_domain=DOMAIN,
                                                            selfsteal_template="docs", tls="internal", firewall=False), db, ADMIN)
    await rw_api.approve(planned["id"], rw_api.ApproveIn(plan_sha256=planned["plan_sha256"]), db, ADMIN)
    out = await run(db, planned["id"])
    assert out["status"] == "succeeded", out["error"]
    assert {"remnanode", "remnawave-selfsteal"} <= containers()

    # An observer without the REALITY keys: Xray forwards the handshake to the SelfSteal socket and the template site answers.
    page = site()
    assert "Документация" in page, page[:300]
    cert = sh("bash", "-c", f"echo | openssl s_client -connect 127.0.0.1:443 -servername {DOMAIN} 2>/dev/null | openssl x509 -noout -ext subjectAltName")
    print("certificate on 443:", cert.strip())
    assert DOMAIN in cert, "the certificate on port 443 is the node domain's, issued by its own Caddy"

    iface = sh("bash", "-c", "ip -o -4 route show default | awk '{print $5; exit}'").strip()
    global_v6 = lambda: "inet6" in sh("ip", "-6", "addr", "show", "dev", iface, "scope", "global")  # noqa: E731
    had_v6 = global_v6()
    print("uplink", iface, "global IPv6 before:", had_v6)
    await module(db, planned["id"], name="ipv6", enabled=False)
    assert sh("sysctl", "-n", "net.ipv6.conf.all.disable_ipv6").strip() == "1"
    assert sh("sysctl", "-n", f"net.ipv6.conf.{iface}.disable_ipv6").strip() == "1", "the uplink itself is switched off too"
    await module(db, planned["id"], name="ipv6", enabled=True)
    assert sh("sysctl", "-n", "net.ipv6.conf.all.disable_ipv6").strip() == "0"
    assert sh("sysctl", "-n", f"net.ipv6.conf.{iface}.disable_ipv6").strip() == "0"
    if had_v6:
        assert global_v6(), "switching IPv6 back on restored the server's global IPv6 address"
    # Diagnostics: the outbound HTTPS the next step needs (GitHub's releases API), right after the IPv6 switch.
    for args in (["curl", "-sS", "-o", "/dev/null", "-w", "%{http_code} %{remote_ip}\n", "--max-time", "15", "https://api.github.com/"],
                 ["curl", "-4", "-sS", "-o", "/dev/null", "-w", "%{http_code} %{remote_ip}\n", "--max-time", "15", "https://api.github.com/"],
                 ["getent", "ahosts", "api.github.com"], ["ip", "-6", "route"], ["ip", "-6", "addr"],
                 ["sudo", "ss", "-ltnp", "sport", "=", ":443"]):
        done = subprocess.run(args, capture_output=True, text=True, timeout=30)
        print("diag", " ".join(args[:2]), "->", done.returncode, (done.stdout + done.stderr).strip()[:600])

    done = await module(db, planned["id"], name="xray_core", version="latest")
    version = next(s for s in done["steps"] if s["kind"] == "node_module")["title"]
    print("core:", version, sh("sudo", "docker", "exec", "remnanode", "xray", "version").splitlines()[:1])
    assert "/usr/local/bin/xray" in sh("sudo", "docker", "inspect", "-f", "{{range .Mounts}}{{.Destination}} {{end}}", "remnanode")
    await module(db, planned["id"], name="xray_core", enabled=False)
    assert "/usr/local/bin/xray" not in sh("sudo", "docker", "inspect", "-f", "{{range .Mounts}}{{.Destination}} {{end}}", "remnanode")
    assert "Документация" in site(), "the bundled core serves the masking again"

    pulled = subprocess.run(["sudo", "docker", "pull", "-q", rw_plan.CHECKER_IMAGE], capture_output=True, text=True, timeout=300)
    by_digest = rw_plan.CHECKER_IMAGE.split(":v", 1)[0] + "@" + rw_plan.CHECKER_IMAGE.rsplit("@", 1)[-1]
    digest = sh("sudo", "docker", "image", "inspect", "-f", "{{index .RepoDigests 0}}", by_digest).strip()
    print(f"Xray Checker image {rw_plan.CHECKER_IMAGE}: pull {pulled.returncode}, {digest or pulled.stderr.strip()}")
    with open(os.environ.get("GITHUB_STEP_SUMMARY", os.devnull), "a") as summary:
        summary.write(f"Xray Checker {rw_plan.CHECKER_IMAGE}: {digest or 'not pulled'}\n")
    assert pulled.returncode == 0 and digest == by_digest, "the pinned Xray Checker image is the one pulled"

    # v28.82.0: transports. The real panel validates the profile (Hysteria2 included) and pushes it to the node.
    from app.remnawave import RemnawaveClient
    panel = RemnawaveClient()
    await module(db, planned["id"], name="transports", transports=["xhttp", "grpc", "hysteria2"])
    assert {"cert.pem", "key.pem"} <= set(sh("sudo", "ls", rw_plan.HYSTERIA_DIR).split()), "the SelfSteal certificate is copied for Hysteria2"
    listening = ""
    for _ in range(30):
        listening = sh("sudo", "ss", "-H", "-lntup")
        if ":4443 " in listening and ":8443 " in listening and any(":443 " in line and line.startswith("udp") for line in listening.splitlines()):
            break
        time.sleep(3)
    print("listening:", [line.split()[:5] for line in listening.splitlines() if any(p in line for p in (":443 ", ":4443 ", ":8443 "))])
    assert ":4443 " in listening and ":8443 " in listening, "xHTTP and gRPC inbounds are up"
    assert any(line.startswith("udp") and ":443 " in line for line in listening.splitlines()), "Hysteria2 listens on UDP 443"
    hosts = await panel._request("GET", "/api/hosts")
    hosts = hosts if isinstance(hosts, list) else hosts.get("hosts", [])
    ports = sorted(h.get("port") for h in hosts if h.get("address") == DOMAIN)
    print("hosts of the node domain:", ports)
    assert ports == [443, 443, 4443, 8443]
    assert "Документация" in site(), "TCP + REALITY with the SelfSteal site still answers"

    await module(db, planned["id"], name="transports", transports=[])
    time.sleep(10)
    listening = sh("sudo", "ss", "-H", "-lntup")
    assert ":4443 " not in listening and ":8443 " not in listening
    hosts = await panel._request("GET", "/api/hosts")
    hosts = hosts if isinstance(hosts, list) else hosts.get("hosts", [])
    assert sorted(h.get("port") for h in hosts if h.get("address") == DOMAIN) == [443]
    assert "Документация" in site()
